import type { ClusterConfigDto, ClusterSavePayload } from '../../../shared/contracts/cluster'
import { defineFakeRoute } from 'vite-plugin-fake-server/client'

const clusterStore = new Map<string, ClusterConfigDto>()

function defaultClusterConfig(instanceId: string, instanceName: string): ClusterConfigDto {
  return {
    instanceId,
    instanceName,
    instanceStatus: 'stopped',
    networkMode: 'offline',
    clusterName: instanceName,
    clusterDescription: 'Generated by BubbleShark Panel',
    clusterPassword: '',
    gameMode: 'survival',
    maxPlayers: 6,
    pvp: false,
    pauseWhenEmpty: true,
    voteEnabled: true,
    clusterIntention: 'cooperative',
    tickRate: 15,
    whitelistSlots: 0,
    maxSnapshots: 6,
    shardEnabled: false,
    bindIp: '127.0.0.1',
    masterIp: '127.0.0.1',
    masterPort: 10888,
    clusterKey: 'supersecretkey',
    steamGroupOnly: false,
    steamGroupId: '0',
    steamGroupAdmins: false,
    clusterTokenConfigured: false,
    clusterTokenMasked: null,
    panelRoomSaved: false,
    configDirty: false,
    // 服务端恒为空数组（说明已内联到页面），fake 保持同形状
    effectiveHints: [],
    warnings: [],
  }
}

export default defineFakeRoute([
  {
    url: '/fake/app/instance/cluster/online-players',
    method: 'get',
    response: ({ query }) => {
      const instanceId = typeof query.instanceId === 'string' ? query.instanceId : ''
      const existing = clusterStore.get(instanceId)
      const running = existing?.instanceStatus === 'running'
      return {
        error: '',
        status: 1,
        data: {
          instanceId,
          running,
          onlinePlayerCount: running ? 3 : null,
          // fake 也给出明细，开发模式下「在线玩家」卡片才有内容可看；
          // 其中一位是离线 / 局域网进来的路人（游戏临时给 ID），用来核对「临时身份」的呈现
          players: running
            ? [
                { kuId: 'KU_fake0001', name: '玩家甲', kleiAccount: true, key: 'ku_fake0001' },
                { kuId: 'KU_fake0002', name: '玩家乙', kleiAccount: true, key: 'ku_fake0002' },
                { kuId: 'Player_3', name: '路人', kleiAccount: false, key: 'player_3' },
              ]
            : null,
          unlistedPlayerCount: 0,
          partial: false,
          maxPlayers: existing?.maxPlayers ?? 6,
        },
      }
    },
  },
  {
    url: '/fake/app/instance/cluster',
    method: 'get',
    response: ({ query }) => {
      const instanceId = typeof query.instanceId === 'string' ? query.instanceId : ''
      const existing = clusterStore.get(instanceId)
      if (existing) {
        return { error: '', status: 1, data: existing }
      }
      const data = defaultClusterConfig(instanceId, `实例 ${instanceId.slice(0, 8)}`)
      clusterStore.set(instanceId, data)
      return { error: '', status: 1, data }
    },
  },
  {
    url: '/fake/app/instance/cluster',
    method: 'put',
    response: ({ body }) => {
      const payload = body as ClusterSavePayload
      const instanceId = payload.instanceId?.trim() ?? ''
      if (!instanceId) {
        return { error: '实例 ID 不能为空', status: 1, data: {} }
      }
      if (payload.networkMode === 'public' && !payload.clusterToken?.trim()) {
        const existing = clusterStore.get(instanceId)
        if (!existing?.clusterTokenConfigured) {
          return { error: '公网模式必须提供有效的 Klei 集群令牌', status: 1, data: {} }
        }
      }
      const previous = clusterStore.get(instanceId) ?? defaultClusterConfig(instanceId, payload.clusterName)
      const newToken = payload.clusterToken?.trim() ?? ''
      const tokenConfigured = payload.networkMode === 'public'
        ? Boolean(newToken || previous.clusterTokenConfigured)
        : false
      const clusterTokenMasked = newToken
        ? `pds-****${newToken.slice(-4)}`
        : (tokenConfigured ? previous.clusterTokenMasked : null)
      const next: ClusterConfigDto = {
        ...previous,
        networkMode: payload.networkMode,
        clusterName: payload.clusterName,
        clusterDescription: payload.clusterDescription,
        clusterPassword: payload.clusterPassword,
        gameMode: payload.gameMode,
        maxPlayers: payload.maxPlayers,
        pvp: payload.pvp,
        pauseWhenEmpty: payload.pauseWhenEmpty,
        voteEnabled: payload.voteEnabled,
        clusterIntention: payload.clusterIntention,
        tickRate: payload.tickRate,
        whitelistSlots: payload.whitelistSlots ?? previous.whitelistSlots,
        maxSnapshots: payload.maxSnapshots,
        shardEnabled: payload.shardEnabled,
        bindIp: payload.bindIp,
        masterIp: payload.masterIp,
        masterPort: payload.masterPort,
        clusterKey: payload.clusterKey,
        steamGroupOnly: payload.steamGroupOnly,
        steamGroupId: payload.steamGroupId,
        steamGroupAdmins: payload.steamGroupAdmins,
        clusterTokenConfigured: tokenConfigured,
        clusterTokenMasked,
        panelRoomSaved: true,
        configDirty: previous.instanceStatus === 'running',
        effectiveHints: [],
        warnings: payload.networkMode === 'public' && !tokenConfigured
          ? ['公网模式但未配置有效的 Klei 集群令牌']
          : [],
      }
      clusterStore.set(instanceId, next)
      return {
        error: '',
        status: 1,
        data: {
          saved: true,
          restarted: Boolean(payload.restart),
        },
      }
    },
  },
])
